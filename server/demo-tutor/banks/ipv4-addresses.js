function classQ(id, ip, answer, defaultMask) {
  return Q(
    id,
    `按历史有类编址，${ip}属于哪类？本题只判断地址类别，不推断当前网络的实际掩码。`,
    answer,
    `第一字节${ip.split(".")[0]}处于${answer}的历史范围；实际CIDR前缀仍应使用题目或配置明确给出的值。`,
    ["A类", "B类", "C类", "D类"]
      .filter((v) => v !== answer)
      .map((v, i) =>
        W(
          v,
          `ipv4-class-${i}`,
          "第一字节的边界判断错了",
          `${v}与本地址的高位模式不符。历史A/B/C/D起始高位分别是0、10、110、1110。`,
          `先把第一字节换成二进制；${defaultMask}不是当前配置的自动结论。`,
        ),
      ),
  );
}
