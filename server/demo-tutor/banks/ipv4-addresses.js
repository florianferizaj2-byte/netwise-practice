function subnetQ(id, ip, prefix, kind, expected, wrongValues) {
  const title = {
    network: "网络地址",
    broadcast: "定向广播地址",
    hosts: "普通可分配主机数",
  }[kind];
  return Q(
    id,
    `普通IPv4多访问子网，地址${ip}/${prefix}。本题只扣除网络和广播两个地址，不另扣网关；${title}是多少？`,
    expected,
    `按/${prefix}的固定前缀和${32 - prefix}个主机位计算；不要套历史默认掩码，也不要仅看最后一个十进制字节。`,
    wrongValues.map(([value, reason, hint], i) =>
      W(value, `ipv4-${kind}-${i}`, "子网边界或计数条件判断错误", reason, hint),
    ),
  );
}
