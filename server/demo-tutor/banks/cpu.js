function busRoleQ(id, scene, role) {
  const defs = {
    地址总线: "表示要访问的位置。",
    数据总线: "承载传输的数据或指令内容。",
    控制总线: "承载读写等控制与时序信号。",
  };
  return Q(id, scene, role, defs[role], [
    ...Object.keys(defs)
      .filter((r) => r !== role)
      .map((r) =>
        W(
          r,
          "bus-role-as-" +
            { 地址总线: "address", 数据总线: "data", 控制总线: "control" }[r],
          `把当前信号归入${r}`,
          `${defs[r]}题设信号的作用是${defs[role]}`,
          "先问信号表达位置、内容还是控制。",
        ),
      ),
    W(
      "地址、数据、控制三者完全没有功能区别",
      "bus-role-same",
      "忽略了逻辑职责",
      "实际信号可以复用引脚，但这三种逻辑功能仍需区分。",
      "逻辑分类不等于物理线束一定独立。",
    ),
  ]);
}
function bandwidthQ(id, width, mhz, transfers) {
  const bytes = width / 8,
    answer = bytes * mhz * transfers;
  return Q(
    id,
    `${width}位数据总线，时钟${mhz}MHz，每周期有效传输${transfers}次。忽略全部开销，十进制理论峰值是多少MB/s？`,
    answer + "MB/s",
    `每次${bytes}字节，每秒${mhz}×10^6×${transfers}次，峰值${answer}×10^6 B/s=${answer}MB/s。`,
    [
      W(
        answer * 8 + "MB/s",
        "bus-bits-bytes",
        "忘了位转字节",
        "按位计算得到的是Mbit/s，若结果写MB/s必须先除8。",
        "先把每次传输宽度转换成字节。",
      ),
      W(
        mhz * transfers + "MB/s",
        "bus-width-omitted",
        "每次传输误当只有1字节",
        `每次实际有${bytes}字节，不是固定1字节。`,
        "频率与每次数据量都要计入。",
      ),
      W(
        answer / 1000000 + "MB/s",
        "bus-mega-conversion",
        "把MHz或MB的百万前缀处理错了",
        "MHz是每秒百万次，十进制MB是百万字节，两者相消后得到当前整数MB/s。",
        "写基本单位B/s后再换成MB/s。",
      ),
    ],
  );
}
function addressRangeQ(id, n) {
  const bytes = 2 ** n;
  return Q(
    id,
    `逻辑地址宽度${n}位，按字节寻址，全部地址可用。最多区分多少字节地址空间？`,
    bytes + "字节",
    `2^${n}个地址，每地址1字节，因此为${bytes}字节。`,
    [
      W(
        bytes * 8 + "字节",
        "bus-address-bit-byte",
        "把每字节的8位又乘进地址数量",
        "题设每地址已经对应一个字节，不需再乘8得到字节数。",
        "地址数量和每地址单位分开。",
      ),
      W(
        n + "字节",
        "bus-address-count",
        "把位数当地址组合数",
        `${n}位地址可形成2^${n}种组合，而不是${n}种。`,
        "地址数量使用2的幂。",
      ),
      W(
        bytes / 2 + "字节",
        "bus-address-sign",
        "给地址额外留了符号位",
        "本题地址所有位都参与寻址，不按补码保留符号。",
        "使用全部地址位。",
      ),
    ],
  );
}
