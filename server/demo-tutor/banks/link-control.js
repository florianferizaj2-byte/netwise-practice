function retrans(id, scheme, frames, lost) {
  const later = frames.filter((f) => f > lost),
    required = scheme === "GBN" ? frames.filter((f) => f >= lost) : [lost];
  return Q(
    id,
    `教材${scheme}模型：已发送帧${frames.join("、")}，帧${lost}丢失，后续${later.join("、")}均到达。接收方按该模型处理乱序帧；${scheme === "GBN" ? "此前已按序确认较早帧，尚无推进发送基序号的新累积确认" : "发送方已收到除丢失帧外其余帧的分别确认"}，丢失帧计时器超时。需要重传哪些已发送帧？`,
    required.join("、"),
    scheme === "GBN"
      ? "GBN接收窗口为1，丢失帧后的乱序帧被丢弃；超时回退重传从当前最早未确认帧起的已发送帧。"
      : "选择重传可缓存并分别确认窗口内后续帧，本题仅丢失帧未确认，因此只补发它。",
    [
      W(
        scheme === "GBN"
          ? String(lost)
          : frames.filter((f) => f >= lost).join("、"),
        "arq-other-scheme",
        "两种乱序处理方式不同",
        scheme === "GBN"
          ? "只补丢失帧是本题SR式处理；GBN已丢弃后续乱序帧。"
          : "全段重传是本题GBN式处理；SR保留并确认了后续窗口内帧。",
        "先问接收方是否缓存后续帧。",
      ),
      W(
        later.join("、"),
        "arq-skip-missing",
        "没有补上真正缺失的帧",
        "仅重传后续帧不能填补当前缺口。",
        "先圈出最早缺失的帧。",
      ),
      W(
        "无需重传",
        "arq-no-retry",
        "本题缺口尚未被可靠填补",
        "题设丢失帧超时且没有覆盖它的有效确认。",
        "核对丢失、确认与超时条件。",
      ),
    ],
  );
}
function windowQ(id, m, scheme) {
  const space = 2 ** m,
    max = scheme === "GBN" ? space - 1 : space / 2;
  return Q(
    id,
    `教材${scheme}协议使用${m}bit模序号。${scheme === "GBN" ? "接收窗口为1" : "发送与接收窗口大小相等"}，按避免新旧序号混淆的标准限制，发送窗口最大是多少？`,
    String(max),
    scheme === "GBN"
      ? `序号空间${space}，GBN发送窗口最大2^m−1=${max}。`
      : `等大的SR窗口要求每个不超过序号空间一半，最大2^(m−1)=${max}。`,
    [
      W(
        String(space),
        "arq-window-full",
        "占满序号空间会产生歧义",
        "不能让该教材模型的窗口占满所有序号。",
        "先算序号空间，再应用协议约束。",
      ),
      W(
        String(scheme === "GBN" ? space / 2 : space - 1),
        "arq-window-other",
        "不要互换GBN与等窗SR限制",
        scheme === "GBN"
          ? "GBN接收窗为1，其发送窗上限不是等窗SR的一半限制。"
          : "2^m−1是GBN接收窗为1的典型限制，不是等窗SR上限。",
        "先确认接收窗口是否为1。",
      ),
      W(
        String(m),
        "arq-window-bits",
        "序号位数不是窗口帧数",
        "m比特表示2^m个模序号；窗口上限再根据协议确定。",
        "把位数、序号空间和窗口帧数分开。",
      ),
    ],
  );
}
