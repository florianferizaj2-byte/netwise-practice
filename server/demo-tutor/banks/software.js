function boundaryQ(id, low, high) {
  const correct = [low - 1, low, low + 1, high - 1, high, high + 1].join("、");
  return Q(
    id,
    `整数输入合法范围${low}～${high}（含两端），本题要求三值边界分析：每界取边界及紧邻内外值。哪组完整满足？`,
    correct,
    "下界取外、界、内；上界取内、界、外。按题设整数步长1构造六个不同值。",
    [
      W(
        [low - 1, low, high, high + 1].join("、"),
        "boundary-two-not-three",
        "用了较少的二值边界集合",
        "这组可覆盖边界两侧，但缺少本题三值方式要求的边界内侧邻值。",
        "本题明确三值，不把其他方式当成通用错误。",
      ),
      W(
        [low, high].join("、"),
        "boundary-only-endpoints",
        "只取边界，漏掉相邻值",
        "题设还要求紧邻边界内外的值。",
        "每界检查外、界、内三点。",
      ),
      W(
        [low + 1, Math.floor((low + high) / 2), high - 1].join("、"),
        "boundary-only-inside",
        "只测区间内部，没有完整边界",
        "内部代表值不能替代边界与边界外值。",
        "先列两端，再补各自邻值。",
      ),
    ],
  );
}
