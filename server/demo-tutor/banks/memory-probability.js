function hitQ(id, h, total) {
  return Q(
    id,
    `Cache共访问${total}次，其中命中${h}次。命中率是多少？`,
    (h / total) * 100 + "%",
    `命中次数÷总访问次数=${h}/${total}=${(h / total) * 100}%。`,
    [
      W(
        ((total - h) / total) * 100 + "%",
        "cache-miss-as-hit",
        "把未命中率当成命中率",
        `未命中${total - h}次，对应${((total - h) / total) * 100}%；题目问命中。`,
        "分子取命中次数。",
      ),
      W(
        ((h / (total - h)) * 100).toFixed(1) + "%",
        "cache-wrong-denominator",
        "分母用了未命中次数",
        "命中率分母是全部访问，不是只取未命中访问。",
        "分母同时包括命中与未命中。",
      ),
      W(
        "100%",
        "cache-all-hit",
        "把访问Cache等同于命中",
        "先查询Cache不意味着每次能找到数据；未命中仍需访问下一级。",
        "区分查询动作与命中结果。",
      ),
    ],
  );
}
function amatQ(id, h, t, penalty) {
  const answer = t + (1 - h) * penalty,
    omit = h * t + (1 - h) * penalty,
    flipped = t + h * penalty;
  return Q(
    id,
    `顺序查Cache模型：命中率${h * 100}%，命中时间${t}ns，未命中额外开销${penalty}ns。平均访存时间是多少？`,
    Number(answer.toFixed(4)) + "ns",
    `AMAT=${t}+(1−${h})×${penalty}=${Number(answer.toFixed(4))}ns。额外开销只在未命中时付出，但每次都要查Cache。`,
    [
      W(
        Number(omit.toFixed(4)) + "ns",
        "cache-omit-hit-time",
        "未命中时漏了Cache查询时间",
        "未命中分支用t+额外开销，不是只用额外开销。",
        "写h×t+(1−h)×(t+penalty)。",
      ),
      W(
        Number(flipped.toFixed(4)) + "ns",
        "cache-hit-miss-reverse",
        "把命中率乘在未命中开销上",
        "额外开销发生概率为1−h，不能用h。",
        "先标出哪个分支产生额外开销。",
      ),
      W(
        t + penalty + "ns",
        "cache-worst-average",
        "用最慢分支代替了平均",
        "每次未命中才需要全部开销；命中只需t。",
        "用各分支概率加权。",
      ),
    ],
  );
}
