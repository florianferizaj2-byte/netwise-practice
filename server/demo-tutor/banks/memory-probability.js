function errorProbability(id, p, n) {
  const correct = 1 - (1 - p) ** n,
    fmt = (x) => x.toFixed(4);
  return Q(
    id,
    `每位错误概率p=${p}，一帧含${n}位，各位错误独立。至少一位错误的概率约是多少（四位小数）？`,
    fmt(correct),
    `先求全部正确概率(1−${p})^${n}，再取补：1−(1−${p})^${n}≈${fmt(correct)}。`,
    [
      W(
        fmt(1 - correct),
        "frame-correct-vs-error",
        "算出了帧正确概率",
        "(1−p)^n是所有位都正确的概率；题目问至少一个错误，需要用1减去它。",
        "先写“全对”，再用补事件得到“至少一错”。",
      ),
      W(
        fmt(p),
        "frame-bit-vs-frame",
        "把位错误率当成帧错误率",
        `p=${p}只针对单个比特，而${n}位组成的帧只要其中任意一位出错就算错。`,
        "确认概率描述的是一个比特还是整帧。",
      ),
      W(
        fmt(p * n),
        "frame-np-exact",
        "把np近似当成精确结果",
        `np=${fmt(p * n)}只有在np很小时才能近似帧错误率；四位小数的精确结果应按1−(1−p)^n算。`,
        "有精度要求时使用完整公式。",
      ),
    ],
  );
}
