const binary = (id, prompt, bits) => {
  const value = parseInt(bits, 2),
    reverse = parseInt([...bits].reverse().join(""), 2);
  return Q(
    id,
    prompt,
    String(value),
    `${bits}₂按位权求和得到${value}；从右端开始，权值为1、2、4、8……。`,
    [
      W(
        String(reverse),
        "weight-order",
        "把位权方向倒过来了",
        `最低位在右边。将${bits}反向读取会得到${reverse}，不是原来的数。`,
        "从最右端的2^0开始标记位权。",
      ),
      W(
        String(value - 1),
        "omit-unit",
        "漏掉了最低位的贡献",
        `这组数的最低位为1；计算总和时不能漏掉该位贡献的1。正确总和是${value}。`,
        "把每个为1的位及其权值逐项列出。",
      ),
      W(
        String(2 ** (bits.length - 1)),
        "highest-only",
        "只计算了最高位",
        `除最高位外，其他为1的位也贡献数值。不能只保留最高位的权值；本题总和为${value}。`,
        "按所有为1的位求和，而不是只看最高位。",
      ),
    ],
  );
};
