function capacityQ(id, need) {
  let h = 2;
  while (2 ** h - 2 < need) h++;
  const p = 32 - h;
  return Q(
    id,
    `普通IPv4多访问子网需至少${need}个可分配主机地址，包含网关的需求已计入，不另预留增长。选择满足需求且地址块最小的前缀。`,
    `/${p}`,
    `/${p}有${2 ** h - 2}个可分配地址，/${p + 1}只有${2 ** (h - 1) - 2}个，故选最长且足够的前缀。`,
    [
      W(
        `/${p + 1}`,
        "vlsm-capacity-small",
        "地址总量够不等于主机容量够",
        "这个更小块扣除网络和广播后不满足需求。",
        "先算普通可分配数量。",
      ),
      W(
        `/${p - 1}`,
        "vlsm-capacity-large",
        "满足需求但不是最小块",
        "这个更大块可用，但题目要求最小足够地址块。",
        "比较相邻前缀的容量。",
      ),
      W(
        `/${h}`,
        "vlsm-hostbits-prefix",
        "主机位数不是前缀长度",
        "选出的h是主机位数量，前缀应为32−h。",
        "分别写出前缀位与主机位。",
      ),
    ],
  );
}
function splitQ(id, parent, child) {
  const count = 2 ** (child - parent);
  return Q(
    id,
    `将一个对齐/${parent} IPv4地址块完整等长划分为/${child}子网，所有子网块均计入，可得到多少个子网？`,
    `${count}个`,
    `借用${child - parent}位作为子网编号，共2^${child - parent}=${count}个子网；不扣编号全0或全1的子网。`,
    [
      W(
        `${count - 2}个`,
        "vlsm-subnet-subtract",
        "对子网数量误减了2",
        "现代无类划分计入全部子网块；主机保留地址规则不等于保留首尾子网。",
        "区分子网数量与每个子网主机数量。",
      ),
      W(
        `${count * 2}个`,
        "vlsm-subnet-extra-bit",
        "多借了一位",
        "前缀差只包含题设的这些位。",
        "计算子前缀减父前缀。",
      ),
      W(
        `${2 ** (32 - child)}个`,
        "vlsm-subnet-hosts",
        "把每块地址数当成块数",
        "2^(32−子前缀)是每个子块的地址总量。",
        "父块总量除以子块总量。",
      ),
    ],
  );
}
function allocationQ(id, parent, allocated, need, correct, wrong) {
  return Q(
    id,
    `在${parent}内，已分配${allocated}。下一普通多访问子网需至少${need}个可分配主机地址（含网关，不另预留）。按地址递增取第一个可用对齐位置，使用最小足够块，应选择哪项？`,
    correct,
    "分别检查容量、规范网络起点、与已分配块不重叠以及不超出父块；四项都满足才可分配。",
    wrong.map(([t, k, title, reason, hint]) => W(t, k, title, reason, hint)),
  );
}
