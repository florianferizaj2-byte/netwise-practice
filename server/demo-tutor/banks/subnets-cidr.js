function sizeQ(id, p) {
  const count = 2 ** (32 - p);
  return Q(
    id,
    `IPv4的/${p}前缀覆盖多少个地址？本题计覆盖总量，不计普通可分配主机数。`,
    `${count}个`,
    `32−${p}个非固定地址位，对应2^(32−${p})=${count}个地址。`,
    [
      W(
        `${count - 2}个`,
        "cidr-size-hosts",
        "把覆盖总量与主机容量混淆",
        "路由前缀覆盖量不扣网络或广播地址。",
        "明确计数对象是覆盖量。",
      ),
      W(
        `${count / 2}个`,
        "cidr-size-extra-prefix",
        "多固定了一位",
        "这对应更长一位的前缀覆盖量。",
        "用32减实际前缀。",
      ),
      W(
        `${count * 2}个`,
        "cidr-size-short-prefix",
        "少固定了一位",
        "这对应更短一位的前缀覆盖量。",
        "前缀越短覆盖越大。",
      ),
    ],
  );
}
function exactQ(id, networks, result, wrong) {
  return Q(
    id,
    `仅从地址集合看，将${networks.join("、")}精确合并为一个CIDR，使用规范网络地址/前缀表示，要求不多覆盖任何地址，应选哪项？`,
    result,
    "规范起点对齐、地址集合连续且覆盖总量相等；不同长度的原始前缀也可先合并兄弟块，再检查共同边界。真实发布路由还需拓扑和策略条件。",
    wrong.map((w) => W(...w)),
  );
}
