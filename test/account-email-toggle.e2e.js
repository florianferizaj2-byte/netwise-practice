import { accountTestMailbox } from "./helpers/account-mail.js";
import { dismissLaunchAnnouncement, finishProfileForm } from "./helpers/mobile-profile.js";

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "aceexam-email-off-ui-")), store = createStore(dir), mailbox = accountTestMailbox();
store.register("fixture_owner", "fixture-owner-password-123");
const app = await createApp({ store, production: true, accountSecurity: { enabled: false, mailer: mailbox } });
const server = app.listen(0, "127.0.0.1"); await new Promise(resolve => server.once("listening", resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const report = { passed: false, checks: [], errors: [], mailRequests: 0 };
fs.mkdirSync("test-output", { recursive: true });
let browser, page;
function track(target) {
  target.on("pageerror", error => report.errors.push(error.message));
  target.on("request", request => { if (request.url().includes("/api/auth/email-code")) report.mailRequests++; });
}
try {
  browser = await launchTestBrowser();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(version => { try { localStorage.setItem(`netwise-announcement-v${version}`, "seen"); } catch {} }, JSON.parse(fs.readFileSync("mobile/package.json", "utf8")).version);
  page = await context.newPage(); track(page);
  await page.goto(base); await page.getByRole("button", { name: "登录", exact: true }).first().click();
  let dialog = page.getByRole("dialog", { name: "登录考匠" });
  await expect(dialog.getByLabel("账号", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "忘记密码？" })).toHaveCount(0);
  await dialog.getByRole("button", { name: "第一次来？创建账号", exact: true }).click();
  dialog = page.getByRole("dialog", { name: "创建考匠账号" });
  await expect(dialog.getByRole("button", { name: "创建账号", exact: true })).toBeEnabled();
  await expect(dialog.getByLabel("邮箱", { exact: true })).toHaveCount(0);
  await dialog.getByLabel("账号", { exact: true }).fill("plain_web_fixture");
  await dialog.getByLabel("密码", { exact: true }).fill("fixture-password-123");
  await dialog.getByLabel("确认密码", { exact: true }).fill("fixture-password-123");
  await page.screenshot({ path: "test-output/account-email-off-desktop.png" });
  await dialog.getByRole("button", { name: "创建账号", exact: true }).click();
  await expect(page.locator(".blue-cert-card")).toHaveCount(certificates.length);
  await page.locator('.blue-cert-card').filter({ has: page.locator('input[value="network-engineer"]') }).click();
  await page.getByRole("button", { name: "进入学习", exact: true }).click();
  await expect(page.locator(".blue-home")).toBeVisible();
  await page.goto(base + "/#settings");
  const security = page.getByRole("region", { name: "账号与安全", exact: true });
  await expect(security.getByRole("button", { name: "修改密码", exact: true })).toBeVisible();
  await expect(security.getByRole("button", { name: "绑定邮箱", exact: true })).toHaveCount(0);
  await security.getByRole("button", { name: "修改密码", exact: true }).click();
  await security.getByLabel("当前密码", { exact: true }).fill("fixture-password-123");
  await security.getByLabel("新密码", { exact: true }).fill("web-changed-password-123");
  await security.getByLabel("确认新密码", { exact: true }).fill("web-changed-password-123");
  await security.getByRole("button", { name: "确认修改密码", exact: true }).click();
  await expect(security.getByRole("status")).toContainText("密码已修改");
  assert.ok(store.authenticate("plain_web_fixture", "web-changed-password-123"));
  report.checks.push("Web hides email verification/recovery while password registration and password change work");
  await context.close();

  const narrow = await browser.newContext({ viewport: { width: 375, height: 812 } });
  page = await narrow.newPage(); track(page);
  await page.route("**/api/auth/security-config", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "注册设置读取失败测试" }) }));
  await page.goto(base);
  await expect(page.getByRole("heading", { name: "登录学习账户", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "忘记密码？" })).toHaveCount(0);
  await page.getByRole("button", { name: "还没有学习账户？立即注册", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("注册设置读取失败测试");
  await expect(page.getByRole("button", { name: "注册并开始学习", exact: true })).toBeDisabled();
  await page.unroute("**/api/auth/security-config");
  await page.getByRole("button", { name: "重新读取", exact: true }).click();
  await expect(page.getByRole("button", { name: "注册并开始学习", exact: true })).toBeEnabled();
  await expect(page.getByLabel("邮箱", { exact: true })).toHaveCount(0);
  await page.getByPlaceholder("输入你的学习账号").fill("narrow_plain_fixture");
  await page.getByPlaceholder("至少 8 位字符").fill("fixture-password-123");
  await page.getByPlaceholder("再次输入密码").fill("fixture-password-123");
  await page.getByRole("button", { name: "注册并开始学习", exact: true }).click();
  await expect(page.locator(".blue-cert-card")).toHaveCount(certificates.length); await narrow.close();
  report.checks.push("375px Web registration works without hidden required email fields");

  const mobile = await browser.newContext({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true });
  page = await mobile.newPage(); track(page); await page.goto(base + "/app/"); await dismissLaunchAnnouncement(page);
  await expect(page.getByText("欢迎回来", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "忘记密码？" })).toHaveCount(0);
  await page.getByRole("button", { name: "注册", exact: true }).first().click();
  await expect(page.getByRole("button", { name: "注册", exact: true }).last()).toBeEnabled();
  await expect(page.getByLabel("邮箱", { exact: true })).toHaveCount(0);
  await page.getByLabel("账号", { exact: true }).fill("plain_app_fixture");
  await page.getByLabel("密码", { exact: true }).fill("fixture-password-123");
  await page.getByLabel("确认密码", { exact: true }).fill("fixture-password-123");
  await page.screenshot({ path: "test-output/account-email-off-app-register.png" });
  await page.getByRole("button", { name: "注册", exact: true }).last().click();
  await finishProfileForm(page, "邮箱关闭测试");
  await page.getByText("软考中级网络工程师", { exact: true }).click();
  await page.getByRole("button", { name: "我的导航", exact: true }).click();
  await page.getByRole("button", { name: "账号与安全设置", exact: true }).click();
  await expect(page.getByRole("button", { name: "绑定邮箱", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "修改密码", exact: true }).click();
  await page.getByLabel("当前密码", { exact: true }).fill("fixture-password-123");
  await page.getByLabel("新密码", { exact: true }).fill("app-changed-password-123");
  await page.getByLabel("确认新密码", { exact: true }).fill("app-changed-password-123");
  await page.getByRole("button", { name: "确认修改密码", exact: true }).click();
  await expect(page.getByText(/密码已修改，请重新登录/)).toBeVisible();
  await page.getByRole("button", { name: "重新登录", exact: true }).click();
  await expect(page.getByText("欢迎回来", { exact: true })).toBeVisible();
  await page.getByLabel("账号", { exact: true }).fill("plain_app_fixture");
  await page.getByLabel("密码", { exact: true }).fill("app-changed-password-123");
  await page.getByRole("button", { name: "登录", exact: true }).last().click();
  await expect(page.getByTestId("today-screen")).toBeVisible();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await mobile.close();
  report.checks.push("App shared UI registers without email, changes password, logs out and logs back in");
  assert.equal(mailbox.messages.length, 0); assert.equal(report.mailRequests, 0);
  assert.equal(store.db.prepare("SELECT count(*) AS n FROM account_emails").get().n, 0);
  assert.deepEqual(report.errors, []); report.passed = true;
} catch (error) { report.failure = error.stack; process.exitCode = 1; if (page && !page.isClosed()) await page.screenshot({ path: "test-output/account-email-off-failure.png", fullPage: true }).catch(() => {}); }
finally {
  fs.writeFileSync("test-output/account-email-toggle-report.json", JSON.stringify({ ...report, runAt: new Date().toISOString() }, null, 2));
  await browser?.close(); await app.locals.stop(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); store.db.close();
  assert.equal(path.dirname(dir), os.tmpdir()); assert.ok(path.basename(dir).startsWith("aceexam-email-off-ui-")); fs.rmSync(dir, { recursive: true, force: true });
  console.log(JSON.stringify(report));
}
